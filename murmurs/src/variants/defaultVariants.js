import { defaultParams } from './paramSchema.js';

/**
 * The 20 curated points in parameter space. These are plain data: each entry
 * has the exact shape of a saved preset's params, and each gets its own copy
 * of the defaults so no two variants ever share an object.
 *
 * Groups: 4 boids, 4 vicsek, 4 topological, 4 visual studies, 4 stress cases.
 */
function variant(id, name, params) {
  return Object.freeze({
    id,
    name,
    params: Object.freeze({ ...defaultParams(), ...params }),
  });
}

